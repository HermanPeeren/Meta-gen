<?php

/**
 * Writes `updates.xml` from the component manifest.
 *
 *   php build/update-xml.php
 *
 * Joomla's update server is a file that repeats what the manifest already
 * says - the element, the version, the platform it runs on - next to a URL
 * where the package for that version can be fetched. Repeating it by hand is
 * how a site is offered an update to a version that was never released, or is
 * told an extension needs Joomla 5 long after it stopped running on one. The
 * file this repository shipped said both of those.
 *
 * So it is generated from the manifest rather than edited, and
 * `UpdateServerTest` fails when the committed file and the manifest disagree.
 *
 * The download URL points at a GitHub release named for the version, which is
 * what `build/build.php` produces and what the release is expected to carry.
 */

declare(strict_types=1);

$root     = \dirname(__DIR__);
$manifest = $root . '/src/metagen.xml';

$xml = simplexml_load_file($manifest);

if ($xml === false) {
    fwrite(STDERR, "Cannot read the manifest at {$manifest}.\n");
    exit(1);
}

$version = trim((string) $xml->version);
$element = trim((string) $xml->name);
$name    = 'Meta-gen';

if ($version === '' || $element === '') {
    fwrite(STDERR, "The manifest needs both a version and a name.\n");
    exit(1);
}

// What the extension says it is, read where Joomla reads it. The manifest holds
// a language key rather than a sentence, and this file wants the sentence - so
// it is resolved rather than repeated. Repeated, it said "Model a Joomla
// extension, and generate it", which is Exten-gen's description: this build
// script was ported from there and that line came with it, describing the wrong
// component on the one screen where somebody is deciding whether to install it.
$description = trim((string) $xml->description);

if (preg_match('/^[A-Z0-9_]+$/', $description) === 1) {
    $sys = $root . '/src/administrator/components/' . $element . '/language/en-GB/' . $element . '.sys.ini';
    $ini = is_file($sys) ? (parse_ini_file($sys) ?: []) : [];

    if (!isset($ini[$description])) {
        fwrite(STDERR, "The manifest describes this component as {$description}, which {$sys} does not define.\n");
        exit(1);
    }

    $description = (string) $ini[$description];
}

// What script.php refuses to install below, so the update server cannot offer
// this version to a site that would then reject it.
$script      = (string) file_get_contents($root . '/src/script.php');
$joomlaFloor = preg_match("/minimumJoomlaVersion\s*=\s*'([^']+)'/", $script, $m) ? $m[1] : '';
$phpFloor    = preg_match("/minimumPHPVersion\s*=\s*'([^']+)'/", $script, $m) ? $m[1] : '';

if ($joomlaFloor === '' || $phpFloor === '') {
    fwrite(STDERR, "script.php does not say which Joomla and PHP it needs.\n");
    exit(1);
}

$download = \sprintf(
    'https://github.com/HermanPeeren/Meta-gen/releases/download/v%s/%s-%s.zip',
    $version,
    $element,
    $version
);

// `6.0` becomes `6\..*`: the platform is a regular expression, and a literal
// version would offer the update to one Joomla release only.
$platform = preg_quote(explode('.', $joomlaFloor)[0], '/') . '\..*';

$updates = <<<XML
<?xml version="1.0" encoding="utf-8"?>
<!--
	Generated by build/update-xml.php from src/metagen.xml. Do not edit by
	hand: run the script and commit the result.
-->
<updates>
	<update>
		<name>{$name}</name>
		<description>{$description}</description>
		<element>{$element}</element>
		<type>component</type>
		<client>administrator</client>
		<version>{$version}</version>
		<downloads>
			<downloadurl type="full" format="zip">{$download}</downloadurl>
		</downloads>
		<maintainer>Herman Peeren</maintainer>
		<maintainerurl>https://yepr.nl</maintainerurl>
		<targetplatform name="joomla" version="{$platform}"/>
		<php_minimum>{$phpFloor}</php_minimum>
	</update>
</updates>

XML;

file_put_contents($root . '/updates.xml', $updates);

echo "updates.xml written for {$element} {$version}\n";
